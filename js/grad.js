// Zema go imeto na gradot od URL
var urlParams = new URLSearchParams(window.location.search);
var cityName = urlParams.get("city");
var selectedCity = cities[cityName];


// Funkcija za zemaње podatoci za slikata
function getPhotoData(index) {

    var key = "photo_" + cityName + "_" + index;

    var data = localStorage.getItem(key);

    if (data) {
        return JSON.parse(data);
    }

    return {
        likes: 0,
        dislikes: 0,
        comments: []
    };
}


// Funkcija za zacuvuvanje podatoci
function savePhotoData(index, data) {

    var key = "photo_" + cityName + "_" + index;

    localStorage.setItem(key, JSON.stringify(data));
}


// Funkcija za like
function likeImage(index) {

    var data = getPhotoData(index);

    data.likes++;

    savePhotoData(index, data);

    document.getElementById("likes-" + index).textContent = data.likes;
}


// Funkcija za dislike
function dislikeImage(index) {

    var data = getPhotoData(index);

    data.dislikes++;

    savePhotoData(index, data);

    document.getElementById("dislikes-" + index).textContent = data.dislikes;
}


// Funkcija za dodavanje komentar
function addComment(index) {

    var input = document.getElementById("comment-input-" + index);

    var comment = input.value.trim();

    if (comment == "") {
        return;
    }

    var data = getPhotoData(index);

    data.comments.push(comment);

    savePhotoData(index, data);

    document.getElementById("comments-" + index).innerHTML +=
        "<p>" + escapeHTML(comment) + "</p>";

    input.value = "";
}


// Sprecuva komentarot da se tretira kako HTML kod
function escapeHTML(text) {

    return text.replace(/[&<>"']/g, function(character) {
        return {
            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#39;"
        }[character];
    });
}


